import Link from "next/link";
import { ArrowLeft } from "lucide-react";
import { getAttendanceRange, getStudents } from "@/lib/db";
import { getCourseOptions } from "@/lib/admin-data";
import { daysInMonth, percentColor, studentStats, todayIST } from "@/lib/attendance";
import { PrintButton } from "@/components/admin/PrintButton";
import { SITE_NAME } from "@/lib/seo";

const cell: Record<string, string> = {
  P: "bg-emerald-500 text-white",
  A: "bg-red-500 text-white",
  L: "bg-amber-400 text-amber-950",
};

type Props = {
  markPath: string;
  search: { month?: string; course?: string };
  courseIds?: string[];
  /** Link each student name to their profile (admin only) */
  studentHref?: (id: string) => string;
  generatedBy: string;
};

/** Monthly attendance register used by both the admin and the teacher panel. */
export async function AttendanceReportView({ markPath, search, courseIds, studentHref, generatedBy }: Props) {
  const today = todayIST();
  const month = /^\d{4}-\d{2}$/.test(search.month ?? "") && search.month! <= today.slice(0, 7) ? search.month! : today.slice(0, 7);
  const days = daysInMonth(month);
  const from = `${month}-01`;
  const to = `${month}-${String(days).padStart(2, "0")}`;

  const [students, allCourses] = await Promise.all([getStudents({ courseIds }), getCourseOptions()]);
  const courses = courseIds ? allCourses.filter((c) => courseIds.includes(c.id)) : allCourses;
  const course = courses.some((c) => c.id === search.course) ? search.course! : courses.length === 1 ? courses[0].id : "";
  const courseTitle = Object.fromEntries(courses.map((c) => [c.id, c.title]));

  const candidates = students.filter((s) => courseTitle[s.courseId] && (!course || s.courseId === course) && s.joinDate <= to);
  const book = await getAttendanceRange(from, to, candidates.map((s) => s.id));
  const roster = candidates
    .filter((s) => s.status === "active" || Object.values(book).some((d) => d[s.id]))
    .sort((a, b) => a.name.localeCompare(b.name));

  const dayList = Array.from({ length: days }, (_, i) => `${month}-${String(i + 1).padStart(2, "0")}`);
  const monthLabel = new Date(`${from}T00:00:00`).toLocaleDateString("en-IN", { month: "long", year: "numeric" });
  const totals = roster.reduce(
    (acc, s) => {
      const st = studentStats(book, s.id);
      return { present: acc.present + st.present, absent: acc.absent + st.absent, leave: acc.leave + st.leave };
    },
    { present: 0, absent: 0, leave: 0 },
  );
  const overall = totals.present + totals.absent ? Math.round((totals.present / (totals.present + totals.absent)) * 100) : null;

  return (
    <>
      <div className="mb-6 flex flex-wrap items-end justify-between gap-4 print:hidden">
        <div>
          <Link href={markPath} className="mb-2 inline-flex items-center gap-1 text-sm text-slate-500 hover:text-brand-600">
            <ArrowLeft className="h-4 w-4" /> Mark attendance
          </Link>
          <h1 className="font-display text-3xl font-bold text-brand-950">Attendance Report</h1>
        </div>
        <PrintButton label="Print / Save PDF" />
      </div>

      <form className="mb-6 flex flex-wrap gap-3 rounded-2xl bg-white p-4 shadow-sm ring-1 ring-slate-200 print:hidden">
        <input type="month" name="month" defaultValue={month} max={today.slice(0, 7)} className="rounded-xl border border-slate-200 px-3 py-2 text-sm" aria-label="Month" />
        <select name="course" defaultValue={course} className="min-w-56 flex-1 rounded-xl border border-slate-200 px-3 py-2 text-sm" aria-label="Course">
          {courses.length !== 1 && <option value="">{courseIds ? "All my courses" : "All courses"}</option>}
          {courses.map((c) => (
            <option key={c.id} value={c.id}>{c.title}</option>
          ))}
        </select>
        <button className="rounded-xl bg-slate-900 px-5 py-2 text-sm font-semibold text-white">Generate Report</button>
      </form>

      {/* Print header */}
      <div className="mb-4 hidden print:block">
        <p className="font-display text-2xl font-bold text-brand-900">{SITE_NAME}</p>
        <p className="text-sm text-slate-600">
          Attendance Register · {monthLabel} · {course ? courseTitle[course] : "All courses"} · Generated by {generatedBy} on{" "}
          {new Date().toLocaleDateString("en-IN")}
        </p>
      </div>

      <div className="mb-6 grid grid-cols-2 gap-3 sm:grid-cols-4 print:grid-cols-4">
        {[
          { label: "Students", value: roster.length, cls: "text-slate-900" },
          { label: "Total present", value: totals.present, cls: "text-emerald-600" },
          { label: "Total absent", value: totals.absent, cls: "text-red-600" },
          { label: "Overall attendance", value: overall === null ? "—" : `${overall}%`, cls: percentColor(overall) },
        ].map((x) => (
          <div key={x.label} className="rounded-2xl bg-white p-4 shadow-sm ring-1 ring-slate-200">
            <p className={`text-2xl font-bold ${x.cls}`}>{x.value}</p>
            <p className="text-xs text-slate-500">{x.label}</p>
          </div>
        ))}
      </div>

      <div className="rounded-2xl bg-white shadow-sm ring-1 ring-slate-200">
        <div className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-100 px-5 py-4">
          <h2 className="font-semibold text-slate-900">
            {monthLabel} · {course ? courseTitle[course] : courseIds ? "All my courses" : "All courses"}
          </h2>
          <div className="flex gap-3 text-xs text-slate-500">
            <span className="flex items-center gap-1"><i className="h-3 w-3 rounded bg-emerald-500" /> Present</span>
            <span className="flex items-center gap-1"><i className="h-3 w-3 rounded bg-red-500" /> Absent</span>
            <span className="flex items-center gap-1"><i className="h-3 w-3 rounded bg-amber-400" /> Leave</span>
          </div>
        </div>

        {roster.length === 0 ? (
          <p className="p-16 text-center text-sm text-slate-400">No students for this month.</p>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-xs">
              <thead>
                <tr className="bg-slate-50 text-slate-500">
                  <th className="sticky left-0 z-10 min-w-48 bg-slate-50 px-4 py-2 text-left font-semibold">Student</th>
                  {dayList.map((d) => {
                    const dow = new Date(`${d}T00:00:00`).getDay();
                    return (
                      <th key={d} className={`w-7 px-0.5 py-2 text-center font-medium ${dow === 0 ? "text-red-400" : ""}`}>
                        {Number(d.slice(-2))}
                      </th>
                    );
                  })}
                  <th className="px-2 py-2 text-center font-semibold">P</th>
                  <th className="px-2 py-2 text-center font-semibold">A</th>
                  <th className="px-2 py-2 text-center font-semibold">L</th>
                  <th className="px-3 py-2 text-center font-semibold">%</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {roster.map((s) => {
                  const st = studentStats(book, s.id);
                  return (
                    <tr key={s.id}>
                      <td className="sticky left-0 z-10 bg-white px-4 py-2">
                        {studentHref ? (
                          <Link href={studentHref(s.id)} className="font-medium text-slate-900 hover:text-brand-600">{s.name}</Link>
                        ) : (
                          <span className="font-medium text-slate-900">{s.name}</span>
                        )}
                        <p className="text-[10px] text-slate-400">{s.rollNo} · {courseTitle[s.courseId]}</p>
                      </td>
                      {dayList.map((d) => {
                        const m = book[d]?.[s.id];
                        const sunday = new Date(`${d}T00:00:00`).getDay() === 0;
                        return (
                          <td key={d} className="px-0.5 py-2 text-center">
                            <span className={`mx-auto grid h-6 w-6 place-items-center rounded-md text-[10px] font-bold ${m ? cell[m] : sunday || d > today || d < s.joinDate ? "" : "bg-slate-100 text-slate-300"}`}>
                              {m ?? ""}
                            </span>
                          </td>
                        );
                      })}
                      <td className="px-2 text-center font-semibold text-emerald-600">{st.present}</td>
                      <td className="px-2 text-center font-semibold text-red-600">{st.absent}</td>
                      <td className="px-2 text-center font-semibold text-amber-600">{st.leave}</td>
                      <td className={`px-3 text-center text-sm font-bold ${percentColor(st.percent)}`}>
                        {st.percent === null ? "—" : `${st.percent}%`}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </>
  );
}
